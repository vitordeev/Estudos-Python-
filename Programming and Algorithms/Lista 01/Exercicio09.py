"""9) Peça ao usuário a distância total percorrida (em km) e o total de
combustível gasto (em litros). Calcule e mostre o consumo médio
do veículo (km/l)."""

kms = float(input("Digite o valor percorido em kms : "))
coms = float(input("Digite o valor de combustivel gastado em litros: "))
print(f"O consumo Medio do veiculo foi de {kms / coms}")